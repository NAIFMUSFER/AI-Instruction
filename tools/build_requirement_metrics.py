"""Generate browser requirement vocabulary from the server's versioned contract."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
spec=json.loads((ROOT/'acs_requirement_metrics.json').read_text(encoding='utf-8'))
text='// Generated by tools/build_requirement_metrics.py. Do not edit.\nexport const requirementMetrics=Object.freeze('+json.dumps(spec['metrics'],ensure_ascii=False,sort_keys=True,separators=(',',':'))+');\n'
text+="export const metricLabels=Object.freeze(Object.fromEntries(Object.entries(requirementMetrics).filter(([,v])=>v.brief_supported).map(([k,v])=>[k,v.label_ar])));\n"
(ROOT/'public/app/generated/requirement-metrics.mjs').write_text(text,encoding='utf-8')
